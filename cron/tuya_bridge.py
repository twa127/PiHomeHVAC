def load_keys(cur):
    with open(DEVICES_JSON_PATH) as f:
        cloud_devices = json.load(f)
    by_name = {d["name"]: d for d in cloud_devices}

    cur.execute("SELECT name, mqtt_topic FROM mqtt_devices WHERE brand = 4 AND type = 1;")
    mqtt_device_to_index = dict((d[0], i) for i, d in enumerate(cur.description))
    for dev in cur.fetchall():
        name = dev[mqtt_device_to_index["name"]]
        mqtt_topic = dev[mqtt_device_to_index["mqtt_topic"]]
        cloud = by_name[dev[mqtt_device_to_index["name"]]]
        DEVICES.append({"slug": mqtt_topic.split("/")[1].split("/")[0], "name": name, "ip": cloud["ip"], "id": cloud["id"], "key": cloud["key"], "version": float(cloud.get("version", 3.4))})

def make_tuya_device(dev):
    d = tinytuya.OutletDevice(dev["id"], dev["ip"], dev["key"])
    d.set_version(dev["version"])
    return d


def find_device(slug):
    for dev in DEVICES:
        if dev["slug"] == slug:
            return dev
    return None


def on_connect_1(client, userdata, flags, rc):
    if rc == 0:
        MQTT_CONNECTED = 1
        for dev in DEVICES:
            client.subscribe(f"cmnd/{dev['slug']}/POWER")
        print(f"MQTT connected (rc={rc}), subscribed to {len(DEVICES)} command topics")
    else:
        MQTT_CONNECTED = 0
        print("\nConnection failed\n")

# Function run when the MQTT client disconnects to the brooker for paho-mqtt Version 1
def on_disconnect_1(client, userdata, rc):
    MQTT_CONNECTED = 0
    if rc != 0:
        print("\nUnexpected disconnection.\n")
    else:
        print("\nSuccessfully disconnected from the brooker\n")

# Function run when the MQTT client connect to the brooker for paho-mqtt Version 2
def on_connect_2(client, userdata, flags, reason_code, properties):
    if reason_code.is_failure:
        MQTT_CONNECTED = 0
        print("\nConnection failed\n")
    else:
        # we should always subscribe from on_connect callback to be sure
        # our subscribed is persisted across reconnections.
        MQTT_CONNECTED = 1
        subscribe_topics = []
        for dev in DEVICES:
            subscribe_topics.append((f"cmnd/{dev['slug']}/POWER", 0))
        client.subscribe(subscribe_topics)
        print("\nConnected to broker")
        print("Subscribed to the followint MQTT topics:")
        for topic in subscribe_topics:
            print(topic[0])

# Function run when the MQTT client disconnects to the brooker for paho-mqtt Version 2
def on_disconnect_2(client, userdata, flags, reason_code, properties):
    MQTT_CONNECTED = 0
    if reason_code == 0:
        print("\nSuccessfully disconnected from the broker\n")
    if reason_code > 0:
        print("\nUnexpected disconnection.\n")

def on_message(client, userdata, msg):
    message_str = msg.payload.decode()
    print("\nMQTT message received.")
    print("Topic: %s" % msg.topic)
    print("Message: %s" % message_str)

    # topic shape: cmnd/<slug>/POWER
    slug = msg.topic.split("/")[1]
    dev = find_device(slug)
    if dev is None:
        return

    command = msg.payload.decode().strip().upper()
    if command not in ("ON", "OFF"):
        print(f"Ignoring unrecognised command '{command}' for {slug}")
        return

    dev["tuya"].set_status(command == "ON", switch=1)
    print(f"{slug}: set {command}")

# Function run when the MQTT client publishes a message to the brooker for paho-mqtt Version 2
def on_publish(client, userdata, mid, reason_code, properties):
    # reason_code and properties will only be present in MQTTv5. It's always unset in MQTTv3
    try:
        userdata.remove(mid)
    except KeyError:
        print("on_publish() is called with a mid not present in unacked_publish")
        print("This is due to an unavoidable race-condition:")
        print("* publish() return the mid of the message sent.")
        print("* mid from publish() is added to unacked_publish by the main thread")
        print("* on_publish() is called by the loop_start thread")
        print("While unlikely (because on_publish() will be called after a network round-trip),")
        print(" this is a race-condition that COULD happen")
        print("")
        print("The best solution to avoid race-condition is using the msg_info from publish()")
        print("We could also try using a list of acknowledged mid rather than removing from pending list,")
        print("but remember that mid could be re-used !")

def poll_and_publish(client):
    global paho_version
    global unacked_publish

    for dev in DEVICES:
        try:
            status = dev["tuya"].status()
        except Exception as e:
            print(f"{dev['slug']}: poll failed - {e}")
            continue

        dps = status.get("dps", {})
        power_state = "ON" if dps.get("1") else "OFF"
        payload = {"POWER": power_state}

        if paho_version.find("1.5.0") != -1:
            client.publish(f"tele/{dev['slug']}/STATE", json.dumps(payload), retain=True)
            print(f"{dev['slug']}: published {payload}")
            client.publish(f"tele/{dev['slug']}/SENSOR", json.dumps(dps), retain=True)
            print(f"{dev['slug']}: published {dps}")
        else:
            msg_info_1 = client.publish(f"tele/{dev['slug']}/STATE", json.dumps(payload), qos=1)
            unacked_publish.add(msg_info_1.mid)
            print(f"{dev['slug']}: published {payload}")
            msg_info_2 = client.publish(f"tele/{dev['slug']}/SENSOR", json.dumps(dps), qos=1)
            unacked_publish.add(msg_info_2.mid)
            print(f"{dev['slug']}: published {dps}")
            # Wait for all message to be published
            while len(unacked_publish):
                time.sleep(0.1)
            # Due to race-condition described above, the following way to wait for all publish is safer
            msg_info_1.wait_for_publish()
            msg_info_2.wait_for_publish()


