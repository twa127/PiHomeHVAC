MQTT_CONNECTED = 0
POLL_SECONDS = 45
DEVICES_JSON_PATH = "/home/maxair/devices.json"

# Match each device by the "name" field from the Tuya cloud account (the
# same name tinytuya scan already prints), not by IP or device ID - those
# live in devices.json and get merged in at startup by load_keys().
#
# Only switch state (dp 1) is polled/published. Energy monitoring (dps
# 17-20) was dropped: MaxAir's GUI can't display it, and locally polling
# those DPs appears to interfere with the Tuya app/cloud's own power
# reporting path - the app stopped showing power data once this bridge
# started actively querying the devices.
DEVICES = []

# install Python library
