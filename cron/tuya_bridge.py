"""
tuya_bridge.py

Bridges Tuya-protocol switches to MQTT so MaxAir can control and monitor
them exactly as if they were Tasmota devices (cmnd/tele/stat topic
convention). Local control and polling only - no cloud dependency once
devices.json has been generated by `python3 -m tinytuya wizard`.

Topics per device (slug is the "slug" field below):
    cmnd/<slug>/POWER   - subscribed. Payload "ON" or "OFF".
    stat/<slug>/POWER   - published immediately after acting on a command.
    tele/<slug>/SENSOR  - published every POLL_SECONDS. JSON body, e.g.
                          {"POWER": "ON", "ENERGY": {"Voltage": 240.1,
                          "Current": 0.19, "Power": 45.6, "Total": 12.545}}

    Non-metered devices
    tele/<slug>/STATE  - published every POLL_SECONDS. JSON body, e.g. {"POWER": "ON/OFF"}.
"""

import json
import time

